    public function run(): void
    {
        foreach (self::CATALOGO as $datos) {
            $producto = Producto::create([
                'marca_id' => Marca::where('nombre', $datos['marca'])->firstOrFail()->id,
                'categoria_id' => Categoria::where('nombre', $datos['categoria'])->firstOrFail()->id,
                'nombre' => $datos['nombre'],
                'genero' => $datos['genero'],
                'descripcion' => 'Un perfume con notas de '.implode(', ', $datos['notas']).'.',
                'destacado' => true,
                'activo' => true,
            ]);
            $producto->notas()->sync(Nota::whereIn('nombre', $datos['notas'])->pluck('id'));
            $this->asignarImagen($producto);
        }
    }

    /**
     * Copia la foto del perfume (database/seeders/imagenes/{slug}.jpg) al disco público.
     */
    private function asignarImagen(Producto $producto): void
    {
        $origen = database_path("seeders/imagenes/{$producto->slug}.jpg");

        if (! is_file($origen)) {
            return;
        }

        $destino = "productos/{$producto->slug}.jpg";
        Storage::disk('public')->put($destino, file_get_contents($origen));
        $producto->update(['imagen' => $destino]);
    }
